test('interactive local sandbox work retains resume reconciliation and needs no external launcher receipt',()=>{
  assert.equal(local.eligible_session,'USER_INITIATED_PLATFORM_MANAGED_INTERACTIVE_SESSION');
  assert.equal(local.session_provenance_source,'TRUSTED_PLATFORM_EXECUTION_CONTEXT');
  assert.equal(local.repository_self_assertion_is_session_provenance,false);
  assert.equal(local.repository_policy_validator_attests_runtime_session,false);
  assert.equal(local.missing_or_ambiguous_platform_session_context,'LOCAL_EXCEPTION_UNAVAILABLE');
  assert.deepEqual(local.platform_attestation_contract.required_binding_fields,['issuer','audience','task_id','session_id','repository','worktree_identity','sandbox_identity','capabilities','issued_at','expires_at','signature']);
  assert.deepEqual(local.platform_attestation_contract.allowed_capabilities_exact,['LOCAL_REPOSITORY_READ','LOCAL_REPOSITORY_EDIT','SANDBOXED_TEST_EXECUTION']);
  assert.equal(local.platform_attestation_contract.signature_validation_required,true);
  assert.equal(local.platform_attestation_contract.trust_anchor_controlled_by_platform,true);
  assert.equal(local.platform_attestation_contract.repository_supplied_attestation_authoritative,false);
  assert.equal(local.platform_attestation_contract.runtime_consumer_status,'NOT_IMPLEMENTED');
  assert.equal(local.platform_attestation_contract.without_runtime_consumer,'NO_REPOSITORY_AUTHORITY_GRANTED');
  assert.equal(local.repository_policy_can_authorize_execution_without_platform_consumer,false);
  assert.equal(local.scope,'LOCAL_REPOSITORY_WORKTREE_TESTS_AND_TWO_INTENT_BOUND_GITHUB_OPERATIONS');
  assert.equal(local.resume_reconciliation_still_required,true);
  assert.equal(local.bootstrap_receipt_required,false);
  assert.equal(local.fresh_exact_head_bootstrap_required,false);
  assert.equal(local.allows_local_edits_and_tests,true);
});
test('local exception grants only two authenticated intent-bound GitHub operations and no dispatch',()=>{
  assert.equal(local.allows_agent_dispatch,false);
  assert.equal(local.allows_github_mutation,false);
  assert.deepEqual(local.authorized_github_operations,['INTENT_BOUND_NON_PROTECTED_BRANCH_UPDATE','CREATE_DRAFT_PR']);
  assert.equal(local.github_operation_exception_requires_authenticated_writer_and_exact_intent,true);
  assert.equal(local.authenticated_github_connector_required,true);
  assert.equal(local.external_development_branch_writes_still_require_fresh_exact_head_bootstrap,false);
  assert.equal(local.draft_proposal_and_all_external_effects_still_require_fresh_exact_head_bootstrap,false);
  assert.equal(local.agent_dispatch_and_protected_operations_still_require_fresh_exact_head_bootstrap,true);
  assert.equal(local.grants_new_authority,false);
});
test('local exception does not weaken global bootstrap, readiness, or AI-020 Owner-reserved boundaries',()=>{
  assert.equal(bootstrap.bootstrap_must_load_before_task_execution,true);
  assert.equal(bootstrap.bootstrap_must_load_before_agent_dispatch,true);
  assert.equal(bootstrap.interactive_local_work_is_narrow_task_execution_exception,true);
  assert.equal(registry.mandatory_inheritance.bootstrap_load_before_task_execution_required,true);
  assert.equal(registry.mandatory_inheritance.bootstrap_load_before_agent_dispatch_required,true);
  assert.equal(roles.constitutional_readiness.required_before_task_analysis_or_execution,true);
  assert.equal(roles.constitutional_readiness.required_before_agent_dispatch,true);
  assert.equal(ai020.id,'AI-020');
  assert.equal(ai020.binding.drift_invalidates,true);
  assert.equal(ai020.binding.single_consumption_required,true);
  assert.deepEqual(ai020.approval_quorum.roles,['KPMO']);
  assert.equal(ai020.approval_quorum.minimum,1);
  assert.equal(ai020.approval_quorum.distinct_identities_required,true);
  assert.equal(ai020.approval_quorum.distinct_workflow_refs_required,true);
  assert.equal(ai020.approval_quorum.distinct_signing_keys_required,true);
  for(const field of ['repository_required','base_sha_required','head_sha_required','head_tree_sha_required','scope_digest_required','test_evidence_required','rollback_plan_required','expiry_required']) assert.equal(ai020.binding[field],true,field);
  assert.ok(ai020.owner_reserved_actions.includes('PRODUCTION'));
  assert.ok(ai020.owner_reserved_actions.includes('TRUST_ROOT_OR_RULESET_WEAKENING'));
  assert.equal(Object.hasOwn(local,'owner_reserved_actions'),false);
  assert.equal(Object.hasOwn(local,'grants_owner_authority'),false);
});
